package com.vlesscardvpn.core

/** Selection, a failed check and an attempted-but-inconclusive check are different states. */
object ServiceProbeStatus {
    fun label(required:Boolean,value:Boolean?,note:String?):String = when {
        !required -> "не выбрано"
        value==true && note=="VOICE_AVAILABLE_LOSS" -> "✓ UDP доступен; часть ответов потеряна — качество звонка не подтверждено"
        value==true -> "✓"
        note=="VOICE_INCOMPLETE" -> "UDP-проба не завершена; маршрут не оценён"
        note=="VOICE_NO_RESPONSE" -> "два STUN-узла не подтвердили UDP; это не проверка реального звонка"
        note=="VOICE_LATENCY" -> "UDP доступен, но RTT выше выбранного предела"
        note=="IG_LOGIN" -> "Instagram требует вход/проверку; веб-доступ не подтверждён"
        note=="IG_REDIRECT" -> "Instagram перенаправил запрос; результат неизвестен"
        note=="IG_HTTP" -> "Instagram не выдал публичную страницу; маршрут не оценён"
        note=="IG_FORMAT" -> "ожидаемая страница Instagram не подтверждена"
        note=="YT_RANGE_UNSUPPORTED" -> "YouTube не подтвердил следующие участки видео; устойчивость загрузки неизвестна"
        note=="YT_MEDIA_TRUNCATED" -> "загрузка участка видео оборвалась раньше указанного размера"
        note=="VOICE_UNKNOWN" -> "серия UDP не завершена — качество не подтверждено"
        note=="VOICE_NO_UDP" -> "STUN-узел не ответил через этот маршрут; доступность звонков не подтверждена"
        note=="VOICE_LOSS" -> "в короткой UDP-серии более 5% потерянных ответов"
        note=="VOICE_SLOW" -> "UDP отвечает, но задержка выше порога голосового теста"
        note=="VOICE_UNSTABLE" -> "UDP отвечает, но разброс задержки превышает 80 мс"
        note=="VOICE_CAUTION" -> "UDP отвечает, но качество серии ниже строгого допуска звонков (потери, RTT или разброс)"
        note=="STABILITY_RESPONSE_FAILED" -> "в серии Telegram получен неуспешный ответ"
        note=="STABILITY_INCOMPLETE" -> "серия Telegram не получила три определённых результата"
        note=="STABILITY_SPREAD" -> "Telegram отвечает, но разброс RTT в серии превышает 150 мс"
        note=="STABILITY_LATENCY" -> "Telegram отвечает, но RTT в серии выше выбранного предела"
        value==false -> "проверка не прошла"
        note=="YT_LOGIN_REQUIRED" -> "YouTube требует вход или проверку пользователя; видеотест не подтверждён"
        note=="YT_UNPLAYABLE" -> "YouTube не разрешил воспроизведение тестового видео; маршрут не оценён"
        note=="DISCORD_GATEWAY" -> "Discord API доступен, но WebSocket HELLO не подтверждён"
        note=="YT_SIGNATURE_UNSUPPORTED" -> "видеоссылка требует неподдерживаемой расшифровки подписи YouTube; маршрут не оценён"
        note=="YT_NO_DIRECT_MEDIA" -> "проверка выполнена: прямая ссылка на видео не получена (формат, согласие или ограничения YouTube)"
        note=="DISCORD_HTTP" -> "Discord API не подтвердил проверку (HTTP-ограничение или ошибка ответа)"
        note=="DISCORD_FORMAT" -> "Discord API вернул неподдерживаемый ответ — подтверждения нет"
        note=="YT_HTTP" -> "проверка выполнена: YouTube не выдал видео/страницу"
        note=="YT_FORMAT" -> "проверка выполнена: ответ не является видеоданными"
        note=="TIMEOUT" -> "время проверки истекло — подтверждение не получено"
        note=="CANCELLED" -> "отменена"
        note=="ERROR" -> "ошибка выполнения проверки"
        else -> "проверка запускалась, подтверждение не получено"
    }
}
